"""
Robustness to the latency model.

CHIMERA v5 sizes capacity with p(u) = exp(-k (1 - u)), which is exactly what the reported
simulator produces (exponential service times, slowdown 1/(1-u)). This script re-runs the
held-out cost/SLO frontier sweep under service-time distributions and slowdown laws the
controller does NOT assume, and repeats the equal-CPU comparison in each.

    python src/scripts/robustness.py            # run every scenario, then analyse
    python src/scripts/robustness.py --analyse  # analyse existing results only

Writes results/robustness/sweep_<scenario>.csv and results/robustness/ROBUSTNESS.md.
"""

import argparse
import subprocess
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from src.scripts import analyze_v2 as an                      # noqa: E402
from src.scripts.run_full_evaluation import SWEEP_UTILS        # noqa: E402

OUT = Path('results/robustness')
SEEDS = ['101', '202', '303', '404', '505']
FAMILIES = ['HPA', 'VPA', 'HPA+VPA', 'AAPA', 'MagicScaler-Inspired', 'CHIMERA_v4', 'CHIMERA']
# (name, service-time distribution, slowdown law, what differs from CHIMERA's assumption)
SCENARIOS = [
    ('reported',         'exponential', 'inverse', 'nothing: the model CHIMERA assumes'),
    ('lognormal',        'lognormal',   'inverse', 'heavier service-time tail'),
    ('gamma',            'gamma4',      'inverse', 'lighter service-time tail'),
    ('bimodal',          'bimodal',     'inverse', '10 % slow requests'),
    ('kingman',          'exponential', 'kingman', 'about half the queueing delay'),
    ('steep',            'exponential', 'steep',   'hockey-stick slowdown'),
    ('lognormal_steep',  'lognormal',   'steep',   'both distribution and slowdown law'),
    ('bimodal_kingman',  'bimodal',     'kingman', 'both distribution and slowdown law'),
]


def run_all(workers: int):
    OUT.mkdir(parents=True, exist_ok=True)
    names = [f'{f}@u={u:.2f}' for f in FAMILIES for u in SWEEP_UTILS]
    for name, dist, slow, _ in SCENARIOS:
        out = OUT / f'sweep_{name}.csv'
        if out.exists():
            print(f'{name}: exists, skipping', flush=True)
            continue
        print(f'{name}: running', flush=True)
        subprocess.run([sys.executable, 'src/scripts/run_full_evaluation.py', '--holdout', '--warmup', '20',
                        '--sweep-only', '--seeds', *SEEDS, '--service-dist', dist, '--slowdown-model', slow,
                        '--workers', str(workers), '--configs', *names, '--out', str(out)],
                       check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def v5_vs_v4(sw):
    """v4 is v5 without risk sizing: its SLO interpolated at v5's CPU, per trace."""
    wins, gaps = 0, []
    for wid, g in sw.groupby('workload_id'):
        c = g[g.family == 'CHIMERA'].groupby('knob')[['core_minutes', 'slo_violation_rate']].mean()
        b = g[g.family == 'CHIMERA_v4'].groupby('knob')[['core_minutes', 'slo_violation_rate']].mean().sort_values('core_minutes')
        x, y = b.core_minutes.to_numpy(), np.minimum.accumulate(b.slo_violation_rate.to_numpy())
        gp = [(np.interp(r.core_minutes, x, y) - r.slo_violation_rate) * 100
              for _, r in c.iterrows() if x.min() <= r.core_minutes <= x.max()]
        if gp:
            gaps.append(float(np.mean(gp)))
            wins += gaps[-1] > 0
    return wins, len(gaps), float(np.mean(gaps)) if gaps else float('nan')


def analyse():
    lines = ['# Robustness to the latency model', '',
             'Generated by `src/scripts/robustness.py`. Held-out workloads (five real traces, four held-out '
             'synthetic shapes), 20-minute warm-up, 5 seeds, every controller swept over target utilisation '
             '0.4-0.95. The equal-CPU comparison of `results/REPORT_v5.md` is repeated under each model. '
             'CHIMERA was not re-tuned for any of them.', '',
             'Every service-time distribution has mean 0.1 s of CPU. Slowdown laws: `inverse` 1/(1-u) '
             '(reported); `kingman` 1 + u/(2(1-u)); `steep` 1/(1-u^4).', '',
             '## Equal-CPU wins against the baselines', '',
             '| Scenario | Service time | Slowdown | Differs from CHIMERA\'s assumption in | Trace-baseline wins | Mean gap (pp) | Worst baseline (mean gap, pp) | v5 vs v4 (traces won, mean gap pp) |',
             '|---|---|---|---|---:|---:|---|---|']
    detail = []
    for name, dist, slow, what in SCENARIOS:
        f = OUT / f'sweep_{name}.csv'
        if not f.exists():
            continue
        sw = pd.read_csv(f)
        pt = an.per_trace_matched(sw)
        wins, n = int((pt.gap_pp > 0).sum()), len(pt)
        by = pt.groupby('baseline').gap_pp.mean()
        w4, n4, g4 = v5_vs_v4(sw)
        lines.append(f'| {name} | {dist} | {slow} | {what} | {wins}/{n} | {pt.gap_pp.mean():+.2f} | '
                     f'{by.idxmin()} ({by.min():+.2f}) | {w4}/{n4}, {g4:+.2f} |')
        t = an.equal_cpu_tests(sw)
        t = t[t.set == 'all']
        losses = pt[pt.gap_pp <= 0]
        detail += ['', f'### {name}', '',
                   '| vs | traces won | mean gap (pp) | p (Holm) |', '|---|---:|---:|---:|']
        detail += [f'| {r.baseline} | {r.trace_wins}/{r.traces} | {r.mean_gap:+.2f} | {an.fmt_p(r.p_holm)} |'
                   for r in t.itertuples()]
        if len(losses):
            detail += ['', 'Traces where CHIMERA does not win at equal CPU: ' +
                       '; '.join(f'{r.workload_id} vs {r.baseline} ({r.gap_pp:+.2f} pp)' for r in losses.itertuples()) + '.']
        chim = sw[(sw.family == 'CHIMERA') & (sw.knob.round(2) == 0.50)]
        aapa = sw[(sw.family == 'AAPA') & (sw.knob.round(2) == 0.70)]
        detail += ['', f'Default settings, all traces: CHIMERA {100 * chim.slo_violation_rate.mean():.2f} % at '
                       f'{chim.core_minutes.mean():.0f} core-min; AAPA {100 * aapa.slo_violation_rate.mean():.2f} % at '
                       f'{aapa.core_minutes.mean():.0f} core-min.']
    lines += ['', '"Trace-baseline wins" counts (trace, baseline) pairs whose cost ranges overlap and where '
                  'CHIMERA has fewer SLO violations at the same CPU. The gap is baseline minus CHIMERA, so '
                  'positive is better for CHIMERA.', '', '## Per scenario'] + detail
    (OUT / 'ROBUSTNESS.md').write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print('\n'.join(lines[:10 + len(SCENARIOS)]))


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--analyse', action='store_true')
    ap.add_argument('--workers', type=int, default=10)
    a = ap.parse_args()
    if not a.analyse:
        run_all(a.workers)
    analyse()
