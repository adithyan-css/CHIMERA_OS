"""
Report for the external real traces (NASA and ClarkNet web-server logs, Internet Traffic
Archive). These ten 100-minute windows were fixed by calendar rule before any controller
ran on them and were used in no design round, so this is a clean held-out test on real
workloads.

    python src/scripts/analyze_ext.py     # reads results/results_ext*.csv, writes results/REPORT_ext.md
"""

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import wilcoxon

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from src.scripts import analyze_v2 as an   # noqa: E402

ORDER = ['CHIMERA', 'CHIMERA_v5', 'CHIMERA_v4', 'AAPA', 'KOSMOS', 'HPA+VPA', 'HPA', 'MagicScaler-Inspired', 'VPA']


def main():
    m = pd.read_csv('results/results_ext.csv')
    sw = pd.read_csv('results/results_ext_sweep.csv')
    L = ['# CHIMERA v6 on ten external real traces', '',
         'Generated by `src/scripts/analyze_ext.py`. Workloads: six 100-minute windows of the NASA Kennedy '
         'Space Center web server log (July 1995) and four of the ClarkNet log (August-September 1995), '
         'both from the Internet Traffic Archive, as built by `dataset/tools/ita_to_traces.py`. The windows '
         'were fixed by calendar rule before any controller ran on them and were used in no design round. '
         f'Main comparison: {len(m)} runs, 10 seeds. Frontier sweep: {len(sw)} runs, 5 seeds. '
         'Same protocol as `REPORT_v5.md`: scored window minutes 70-100, 20-minute warm-up, unchanged '
         'controller settings. Request rates are scaled by 3 (NASA) and 1.5 (ClarkNet) so that the busiest minute '
         'fits the 30-replica limit of the horizontal-only baselines at the cheapest sweep setting.', '',
         '## Default settings', '',
         '| Controller | SLO viol. | p99 (s) | CPU (core-min) | actions |', '|---|---:|---:|---:|---:|']
    g = m.groupby('config_name')[['slo_violation_rate', 'p99_response_time', 'core_minutes', 'scaling_actions']].mean()
    for c in ORDER:
        if c in g.index:
            r = g.loc[c]
            L.append(f"| {'**CHIMERA v6**' if c == 'CHIMERA' else c} | {100 * r.slo_violation_rate:.2f}% | "
                     f"{r.p99_response_time:.2f} | {r.core_minutes:.1f} | {r.scaling_actions:.1f} |")

    L += ['', 'Paired tests at default settings, CHIMERA minus baseline (negative = CHIMERA lower): Wilcoxon '
              'signed-rank over (trace, seed) pairs, Holm-corrected within each metric.', '',
          '| vs | SLO diff (pp) | p | CPU diff (core-min) | p | traces with lower SLO |', '|---|---:|---:|---:|---:|---:|']
    ours = m[m.config_name == 'CHIMERA'].set_index(['workload_id', 'seed'])
    rows = []
    for c in ORDER[1:]:
        th = m[m.config_name == c].set_index(['workload_id', 'seed'])
        idx = ours.index.intersection(th.index)
        if not len(idx):
            continue
        ds = ours.loc[idx, 'slo_violation_rate'] - th.loc[idx, 'slo_violation_rate']
        dc = ours.loc[idx, 'core_minutes'] - th.loc[idx, 'core_minutes']
        rows.append([c, 100 * ds.mean(), wilcoxon(ds).pvalue, dc.mean(), wilcoxon(dc).pvalue,
                     int((ds.groupby(level=0).mean() < 0).sum()), ds.index.get_level_values(0).nunique()])
    ps, pc = an.holm([r[2] for r in rows]), an.holm([r[4] for r in rows])
    for r, a_, b_ in zip(rows, ps, pc):
        L.append(f'| {r[0]} | {r[1]:+.2f} | {an.fmt_p(a_)} | {r[3]:+.1f} | {an.fmt_p(b_)} | {r[5]}/{r[6]} |')

    pt = an.per_trace_matched(sw)
    L += ['', '## Equal CPU, trace by trace', '',
          "Each baseline's SLO interpolated on its own frontier at CHIMERA's CPU cost; positive = CHIMERA has "
          'fewer violations. Only traces where the two cost ranges overlap are compared.', '',
          '| vs | traces compared | CHIMERA wins | mean gap (pp) | worst trace (pp) |', '|---|---:|---:|---:|---|']
    for fam, gg in pt.groupby('baseline'):
        w = gg.loc[gg.gap_pp.idxmin()]
        L.append(f'| {fam} | {len(gg)} | {int((gg.gap_pp > 0).sum())}/{len(gg)} | {gg.gap_pp.mean():+.2f} | '
                 f'{w.gap_pp:+.2f} ({w.workload_id}) |')
    L += ['', f'Overall: CHIMERA wins {int((pt.gap_pp > 0).sum())} of {len(pt)} trace-baseline comparisons at equal CPU.']
    lost = pt[pt.gap_pp <= 0]
    if len(lost):
        L += ['', 'Comparisons CHIMERA does not win: ' +
              '; '.join(f'{r.workload_id} vs {r.baseline} ({r.gap_pp:+.2f} pp)' for r in lost.itertuples()) + '.']

    et = an.equal_cpu_tests(sw)
    et = et[et.set == 'all']
    L += ['', 'Significance (one gap per trace and seed, one-sample Wilcoxon, Holm-corrected):', '',
          '| vs | gaps | traces | mean gap (pp) | p (Holm) | traces won |', '|---|---:|---:|---:|---:|---:|']
    L += [f'| {r.baseline} | {r.n} | {r.traces} | {r.mean_gap:+.2f} | {an.fmt_p(r.p_holm)} | {r.trace_wins}/{r.traces} |'
          for r in et.itertuples()]

    def versus(older):
        gaps = []
        for wid, gw in sw.groupby('workload_id'):
            c = gw[gw.family == 'CHIMERA'].groupby('knob')[['core_minutes', 'slo_violation_rate']].mean()
            b = gw[gw.family == older].groupby('knob')[['core_minutes', 'slo_violation_rate']].mean().sort_values('core_minutes')
            x, y = b.core_minutes.to_numpy(), np.minimum.accumulate(b.slo_violation_rate.to_numpy())
            gp = [(np.interp(r.core_minutes, x, y) - r.slo_violation_rate) * 100
                  for _, r in c.iterrows() if x.min() <= r.core_minutes <= x.max()]
            if gp:
                gaps.append(float(np.mean(gp)))
        return f'better on {sum(g > 0 for g in gaps)} of {len(gaps)} traces, mean gap {np.mean(gaps):+.2f} pp'

    L += ['', f"v6 against v5 (narrower dead-band, legacy safety path) at equal CPU: {versus('CHIMERA_v5')}.",
          '', f"v6 against v4 (no risk sizing) at equal CPU: {versus('CHIMERA_v4')}."]

    L += ['', '## Per trace, default settings (SLO violations / CPU core-min)', '',
          '| Trace | CHIMERA v6 | AAPA | KOSMOS | HPA |', '|---|---:|---:|---:|---:|']
    pv = m.groupby(['workload_id', 'config_name'])[['slo_violation_rate', 'core_minutes']].mean()
    for wid in sorted(m.workload_id.unique()):
        cell = lambda c: f"{100 * pv.loc[(wid, c)].slo_violation_rate:.2f}% / {pv.loc[(wid, c)].core_minutes:.0f}"
        L.append(f"| {wid.replace('real_ext_', '')} | {cell('CHIMERA')} | {cell('AAPA')} | {cell('KOSMOS')} | {cell('HPA')} |")
    Path('results/REPORT_ext.md').write_text('\n'.join(L) + '\n', encoding='utf-8', newline='\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
